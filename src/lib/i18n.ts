import { EXTRA } from "./i18n.extra";

/** Hand-written strings per language. Missing keys are filled by Google Translate at runtime. */
const DICTS: Partial<Record<Language, Dict>> & { en: Dict } = {
  en: { ...en, ...EXTRA.en },
  fr: { ...fr, ...EXTRA.fr },
  it: { ...it, ...EXTRA.it },
  ar: { ...ar, ...EXTRA.ar },
  pt: { ...pt, ...EXTRA.pt },
};

/** The full English dictionary — the source we send to the Translation API. */
export function englishDict(): Dict {
  return { ...DICTS.en };
}

/** Runtime overlay of machine-translated UI strings, keyed by language. */
const OVERLAY: Partial<Record<Language, Dict>> = {};

export function setUiOverlay(lang: Language, dict: Dict) {
  OVERLAY[lang] = { ...(OVERLAY[lang] ?? {}), ...dict };
}

/** True when we ship hand-written copy for this language. */
export function hasNativeDict(lang: Language) {
  return Boolean(DICTS[lang]);
}

export function t(lang: Language, key: string): string {
  return DICTS[lang]?.[key] ?? OVERLAY[lang]?.[key] ?? DICTS.en[key] ?? key;
}

/** Same as t(), with {placeholder} substitution. */
export function tf(lang: Language, key: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), t(lang, key));
}

export function isRtl(lang: Language) {
  return lang === "ar";
}

const BADGE_KEYS: Record<string, string> = {
  Scholar: "badge.scholar",
  "Wisdom Seeker": "badge.seeker",
  "Diaspora Builder": "badge.builder",
};

/** Localised label for a stored badge value. */
export function badgeLabel(lang: Language, badge: string): string {
  return BADGE_KEYS[badge] ? t(lang, BADGE_KEYS[badge]) : badge;
}
